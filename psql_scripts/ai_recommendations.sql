-- Get comprehensive recommendations (content + collaborative)
CREATE OR REPLACE FUNCTION get_hybrid_recommendations(
    input_customer_id INTEGER,
    input_product_id INTEGER DEFAULT NULL,
    max_results INTEGER DEFAULT 10
)
RETURNS TABLE(
    product_id BIGINT,
    product_label TEXT,
    brand_label TEXT,
    category_label TEXT,
    recommendation_score NUMERIC(5,4),
    price NUMERIC(10,2),
    recommendation_type TEXT,
    reason TEXT
) AS $$
BEGIN
    RETURN QUERY
    WITH content_based AS (
        SELECT 
            sp.product_id,
            sp.product_label,
            sp.brand_label,
            sp.category_label,
            sp.similarity_score * 0.6 as score, -- Weight content-based at 60%
            sp.price,
            'content_based' as rec_type,
            'Similar to products you viewed: ' || sp.product_label as reason
        FROM find_similar_products(COALESCE(input_product_id, 1), 0.3, 20) sp
        WHERE input_product_id IS NOT NULL
    ),
    collaborative AS (
        SELECT 
            cr.product_id,
            cr.product_label,
            cr.brand_label,
            cr.category_label,
            cr.recommendation_score * 0.4 as score, -- Weight collaborative at 40%
            cr.price,
            'collaborative' as rec_type,
            cr.reason
        FROM get_collaborative_recommendations(input_customer_id, 20) cr
    ),
    combined AS (
        SELECT * FROM content_based
        UNION ALL
        SELECT * FROM collaborative
    ),
    aggregated AS (
        SELECT 
            c.product_id,
            MAX(c.product_label) as product_label,
            MAX(c.brand_label) as brand_label,
            MAX(c.category_label) as category_label,
            SUM(c.score) as final_score,
            MAX(c.price) as price,
            CASE 
                WHEN COUNT(*) > 1 THEN 'hybrid'
                ELSE MAX(c.rec_type)
            END as rec_type,
            STRING_AGG(DISTINCT c.reason, '; ') as combined_reason
        FROM combined c
        GROUP BY c.product_id
    )
    SELECT 
        a.product_id::BIGINT,
        a.product_label,
        a.brand_label,
        a.category_label,
        ROUND(LEAST(a.final_score, 1.0)::NUMERIC, 4) as recommendation_score,
        a.price,
        a.rec_type,
        a.combined_reason
    FROM aggregated a
    ORDER BY recommendation_score DESC
    LIMIT max_results;
END;
$$ LANGUAGE plpgsql;

