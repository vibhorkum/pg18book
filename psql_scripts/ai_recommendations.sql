-- Update customer purchase profiles
CREATE OR REPLACE FUNCTION update_customer_purchase_profiles()
RETURNS INTEGER AS $$
DECLARE
    updated_count INTEGER := 0;
    sales_table_exists BOOLEAN;
BEGIN
    -- Check if sales tables exist
    SELECT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_name = 'sales_transaction' 
        AND table_schema IN ('public', 'west_sales', 'east_sales')
    ) INTO sales_table_exists;
    
    IF NOT sales_table_exists THEN
        RAISE NOTICE 'Sales transaction tables not found. Collaborative filtering features will be limited.';
        RETURN 0;
    END IF;
    
    INSERT INTO customer_purchase_profile (
        customer_id, 
        product_category_id, 
        purchase_frequency, 
        total_spent, 
        avg_rating,
        last_purchase_date,
        preference_score
    )
    SELECT 
        st.customer_id,
        p.product_category_id,
        COUNT(*) as purchase_frequency,
        SUM(stl.price_at_sale * stl.qty) as total_spent,
        COALESCE(AVG(pr.rating), 0) as avg_rating,
        MAX(st.transaction_date) as last_purchase_date,
        -- Preference score based on frequency, spending, and ratings
        LEAST(1.0, (
            (COUNT(*) / 10.0) * 0.4 + 
            (SUM(stl.price_at_sale * stl.qty) / 1000.0) * 0.3 +
            (COALESCE(AVG(pr.rating), 3) / 5.0) * 0.3
        )) as preference_score
    FROM sales_transaction st
    JOIN sales_transaction_line stl ON st.id = stl.sales_transaction_id
    JOIN product_variant pv ON stl.product_variant_id = pv.id
    JOIN product p ON pv.product_id = p.id
    LEFT JOIN product_ratings pr ON st.customer_id = pr.customer_id AND p.id = pr.product_id
    GROUP BY st.customer_id, p.product_category_id
    ON CONFLICT (customer_id, product_category_id)
    DO UPDATE SET
        purchase_frequency = EXCLUDED.purchase_frequency,
        total_spent = EXCLUDED.total_spent,
        avg_rating = EXCLUDED.avg_rating,
        last_purchase_date = EXCLUDED.last_purchase_date,
        preference_score = EXCLUDED.preference_score;
        
    GET DIAGNOSTICS updated_count = ROW_COUNT;
    RETURN updated_count;
END;
$$ LANGUAGE plpgsql;

-- Find customers with similar purchase patterns
CREATE OR REPLACE FUNCTION find_similar_customers(
    input_customer_id INTEGER,
    max_results BIGINT DEFAULT 5
)
RETURNS TABLE(
    customer_id INTEGER,
    similarity_score NUMERIC(5,4),
    shared_categories BIGINT
) AS $$
BEGIN
    RETURN QUERY
    WITH customer_preferences AS (
        SELECT 
            cpp1.customer_id as cust1,
            cpp2.customer_id as cust2,
            COUNT(*) as shared_categories,
            -- Cosine similarity based on preference scores
            (SUM(cpp1.preference_score * cpp2.preference_score) / 
             (SQRT(SUM(cpp1.preference_score * cpp1.preference_score)) * 
              SQRT(SUM(cpp2.preference_score * cpp2.preference_score)))) as similarity
        FROM customer_purchase_profile cpp1
        JOIN customer_purchase_profile cpp2 ON cpp1.product_category_id = cpp2.product_category_id
        WHERE cpp1.customer_id = input_customer_id 
        AND cpp2.customer_id != input_customer_id
        GROUP BY cpp1.customer_id, cpp2.customer_id
        HAVING COUNT(*) >= 2  -- At least 2 shared categories
    )
    SELECT 
        cp.cust2,
        ROUND(cp.similarity::NUMERIC, 4),
        cp.shared_categories
    FROM customer_preferences cp
    WHERE cp.similarity > 0.1
    ORDER BY cp.similarity DESC
    LIMIT max_results;
END;
$$ LANGUAGE plpgsql;

-- Generate collaborative filtering recommendations
CREATE OR REPLACE FUNCTION get_collaborative_recommendations(
    input_customer_id INTEGER,
    max_results INTEGER DEFAULT 10
)
RETURNS TABLE(
    product_id BIGINT,
    product_label TEXT,
    brand_label TEXT,
    category_label TEXT,
    recommendation_score NUMERIC(5,4),
    price NUMERIC(10,2),
    reason TEXT
) AS $$
BEGIN
    RETURN QUERY
    WITH similar_customers AS (
        SELECT * FROM find_similar_customers(input_customer_id, 10)
    ),
    customer_purchased AS (
        SELECT DISTINCT p.id as product_id
        FROM sales_transaction st
        JOIN sales_transaction_line stl ON st.id = stl.sales_transaction_id
        JOIN product_variant pv ON stl.product_variant_id = pv.id
        JOIN product p ON pv.product_id = p.id
        WHERE st.customer_id = input_customer_id
    ),
    recommended_products AS (
        SELECT 
            p.id::BIGINT,
            p.label::TEXT,
            pb.label::TEXT as brand_label,
            pc.label::TEXT as category_label,
            ROUND((AVG(sc.similarity_score * COALESCE(pr.rating, 3) / 5.0))::NUMERIC, 4) as score,
            COALESCE(pvp.price, 0.00) as price,
            'Customers with similar preferences also liked this product' as reason
        FROM similar_customers sc
        JOIN sales_transaction st ON sc.customer_id = st.customer_id
        JOIN sales_transaction_line stl ON st.id = stl.sales_transaction_id
        JOIN product_variant pv ON stl.product_variant_id = pv.id
        JOIN product p ON pv.product_id = p.id
        JOIN product_brand pb ON p.product_brand_id = pb.id
        JOIN product_category pc ON p.product_category_id = pc.id
        LEFT JOIN product_ratings pr ON sc.customer_id = pr.customer_id AND p.id = pr.product_id
        LEFT JOIN product_variant_price pvp ON pv.id = pvp.product_variant_id AND pvp.current = true
        WHERE p.id NOT IN (SELECT cp.product_id FROM customer_purchased cp)
        GROUP BY p.id, p.label, pb.label, pc.label, pvp.price
        HAVING COUNT(*) >= 2  -- Recommended by at least 2 similar customers
    )
    SELECT * FROM recommended_products
    ORDER BY score DESC
    LIMIT max_results;
END;
$$ LANGUAGE plpgsql;

