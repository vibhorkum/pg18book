-- Product embeddings for content-based similarity
CREATE TABLE IF NOT EXISTS product_embeddings (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    embedding_type TEXT NOT NULL DEFAULT 'description', -- 'description', 'attributes', 'combined'
    embedding vector(384), -- Using 384-dimensional embeddings (common for sentence transformers)
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(product_id, embedding_type)
);

-- Customer purchase behavior for collaborative filtering
CREATE TABLE IF NOT EXISTS customer_purchase_profile (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
    product_category_id INTEGER NOT NULL REFERENCES product_category(id),
    purchase_frequency INTEGER DEFAULT 0,
    total_spent NUMERIC(10,2) DEFAULT 0.00,
    avg_rating NUMERIC(3,2) DEFAULT 0.00,
    last_purchase_date DATE,
    preference_score NUMERIC(5,4) DEFAULT 0.00, -- Normalized preference score (0-1)
    UNIQUE(customer_id, product_category_id)
);

-- Product similarity cache for performance
CREATE TABLE IF NOT EXISTS product_similarity_cache (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id_1 INTEGER NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    product_id_2 INTEGER NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    similarity_score NUMERIC(5,4) NOT NULL, -- Cosine similarity score (0-1)
    similarity_type TEXT NOT NULL DEFAULT 'embedding', -- 'embedding', 'collaborative', 'hybrid'
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(product_id_1, product_id_2, similarity_type),
    CHECK(product_id_1 != product_id_2)
);

-- Customer product ratings (for collaborative filtering)
CREATE TABLE IF NOT EXISTS product_ratings (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
    review_text TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(customer_id, product_id)
);

-- Recommendation results cache
CREATE TABLE IF NOT EXISTS recommendation_cache (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
    recommended_product_id INTEGER NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    recommendation_type TEXT NOT NULL, -- 'similar_products', 'collaborative', 'hybrid'
    score NUMERIC(5,4) NOT NULL,
    reason TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours')
