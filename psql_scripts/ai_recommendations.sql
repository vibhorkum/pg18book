-- Find similar products using vector similarity
CREATE OR REPLACE FUNCTION find_similar_products(
    input_product_id INTEGER,
    similarity_threshold FLOAT DEFAULT 0.3,
    max_results INTEGER DEFAULT 10
)
RETURNS TABLE(
    product_id BIGINT,
    product_label TEXT,
    brand_label TEXT,
    category_label TEXT,
    similarity_score NUMERIC(5,4),
    price NUMERIC(10,2)
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        p.id::BIGINT,
        p.label::TEXT,
        pb.label::TEXT,
        pc.label::TEXT,
        ROUND((1 - (pe1.embedding <=> pe2.embedding))::NUMERIC, 4) as similarity_score,
        COALESCE(pvp.price, 0.00) as price
    FROM product_embeddings pe1
    JOIN product_embeddings pe2 ON pe2.embedding_type = pe1.embedding_type
    JOIN product p ON pe2.product_id = p.id
    JOIN product_brand pb ON p.product_brand_id = pb.id
    JOIN product_category pc ON p.product_category_id = pc.id
    LEFT JOIN product_variant pv ON p.id = pv.product_id
    LEFT JOIN product_variant_price pvp ON pv.id = pvp.product_variant_id AND pvp.current = true
    WHERE pe1.product_id = input_product_id
    AND pe2.product_id != input_product_id
    AND (1 - (pe1.embedding <=> pe2.embedding)) >= similarity_threshold
    ORDER BY similarity_score DESC
    LIMIT max_results;
END;
$$ LANGUAGE plpgsql;

-- Search for products similar to a text query
CREATE OR REPLACE FUNCTION search_similar_products_by_text(
    search_text TEXT,
    similarity_threshold FLOAT DEFAULT 0.2,
    max_results BIGINT DEFAULT 10
)
RETURNS TABLE(
    product_id BIGINT,
    product_label TEXT,
    brand_label TEXT,
    category_label TEXT,
    similarity_score NUMERIC(5,4),
    price NUMERIC(10,2)
) AS $$
DECLARE
    search_embedding vector(384);
BEGIN
    -- Generate embedding for search text
    search_embedding := generate_simple_embedding(search_text);
    
    RETURN QUERY
    SELECT 
        p.id::BIGINT,
        p.label::TEXT,
        pb.label::TEXT,
        pc.label::TEXT,
        ROUND((1 - (search_embedding <=> pe.embedding))::NUMERIC, 4) as similarity_score,
        COALESCE(pvp.price, 0.00) as price
    FROM product_embeddings pe
    JOIN product p ON pe.product_id = p.id
    JOIN product_brand pb ON p.product_brand_id = pb.id
    JOIN product_category pc ON p.product_category_id = pc.id
    LEFT JOIN product_variant pv ON p.id = pv.product_id
    LEFT JOIN product_variant_price pvp ON pv.id = pvp.product_variant_id AND pvp.current = true
    WHERE (1 - (search_embedding <=> pe.embedding)) >= similarity_threshold
    ORDER BY similarity_score DESC
    LIMIT max_results;
END;
$$ LANGUAGE plpgsql;

