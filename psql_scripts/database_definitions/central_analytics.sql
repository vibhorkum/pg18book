/* 
================================================================================
  PSQL SCRIPT FOR CENTRAL ANALYTICS DATABASE
================================================================================
  OWNER: Superuser
  PURPOSE: Creates the database schema for central analytics.
           All tables are populated via logical replication.
           All data is read only
  Schemas:
           * api has views to access the data for reporting
             * product_reference has product and pricing data
           * product_reference provides definitions for 
             products and prices into schema product_reference
           * eu_customer holds the customer table replicated from the 
             eu_ecommerce_data database
           * us_customer holds the customer table replicated from the
             us_ecommerce_data database
           * customer_merged holds the customer_merged table that assembles 
             the us and eu customer data, but filters out PII
           * eu_sales holds the eu sales transactions and sales transaction lines
           * us_sales holds the us sales transactions and sales transaction lines 
           * sales_merged holds the sales_transaction_merged and 
             sales_transaction_lines_merged tables that assembles the US and EU
             data
            
================================================================================

================================================================================
  SECTION 1: DATABASE PREPARATION
 =================================================================
 Note: Run this script while connected to a neutral DB (e.g., 'postgres').
*/

\echo '[DATABASE PREP] ==> Preparing to drop and recreate the database.'
-- Terminate all active connections to the target database before dropping it.
-- This is a more controlled approach than using WITH (FORCE).
SELECT pg_terminate_backend(pid)
FROM pg_stat_activity
WHERE datname = 'central_analytics' AND pid <> pg_backend_pid();

DROP DATABASE IF EXISTS central_analytics;

\echo '[DATABASE PREP] ==> Creating the database...'
CREATE DATABASE central_analytics;

-- Switch connection to the newly created database.
\c central_analytics

CREATE SCHEMA api;
CREATE SCHEMA product_reference;
CREATE SCHEMA eu_customer;
CREATE SCHEMA us_customer;
CREATE SCHEMA customer_merged;
CREATE SCHEMA eu_sales;
CREATE SCHEMA us_sales;
CREATE SCHEMA sales_merged;

\echo '--> Creating the search path at the database level'

ALTER DATABASE central_analytics SET SEARCH_PATH TO api, product_reference, customer_merged, sales_merged; -- permanent change
SET SEARCH_PATH TO api, product_reference, customer_merged, sales_merged;  --- make sure path is available in current session

-- =================================================================
--  SECTION 2: PRODUCT REFERENCE DATA
-- =================================================================
-- These tables will be populated by logical replication from the
-- 'ecommerce_reference_data' database. Their structure must match
-- the publisher's definition exactly. Do NOT insert data manually.
-- =================================================================


CREATE TABLE product_reference.product_category (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    label VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE product_reference.product_brand (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    label VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE product_reference.product (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_category_id INTEGER NOT NULL REFERENCES product_reference.product_category (id),
    product_brand_id INTEGER NOT NULL REFERENCES product_reference.product_brand (id),
    label VARCHAR(50) NOT NULL,
    shortdescription VARCHAR(200) NOT NULL,
    longdescription TEXT,
    image_filename VARCHAR(50)
);


/*
removed the two integrity constraints for geo/currency and validity
as those are checked at the source
*/

CREATE TABLE product_reference.product_price (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER NOT NULL REFERENCES product_reference.product (id) ON DELETE CASCADE,
    price NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    currency VARCHAR(4) NOT NULL,
    geography VARCHAR(4) NOT NULL,
    -- DATERANGE where the lower bound is inclusive, and the upper bound is exclusive.
    validity DATERANGE NOT NULL,
    current BOOLEAN NOT NULL DEFAULT false
);

-- =================================================================
--  SECTION 2: CUSTOMER DATA
-- =================================================================

-- replicated data from the US

CREATE TABLE us_customer.customer (
    id UUID PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_numbers JSONB,
    street_address VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(50) NOT NULL
);

-- replicated data from the EU

CREATE TABLE eu_customer.customer (
    id UUID PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_numbers JSONB,
    street_address VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(50) NOT NULL
);

-- merged customer data data from the EU and US

CREATE TABLE customer_merged.customer_merged (
    id UUID,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_numbers JSONB,
    street_address VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(50) NOT NULL
)
PARTITION BY LIST (country);


ALTER TABLE customer_merged.customer_merged ATTACH PARTITION eu_customer.customer DEFAULT;
ALTER TABLE customer_merged.customer_merged ATTACH PARTITION us_customer.customer FOR VALUES IN ('US', 'us');


-- =================================================================
--  SECTION 2: SALES DATA
-- =================================================================

-- replicated data from the US
-- add an origin column to be able to use it as a partion

CREATE TABLE us_sales.sales_transaction (
    id UUID,
    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_id UUID,
    origin VARCHAR(4) DEFAULT 'US'
);

CREATE TABLE us_sales.sales_transaction_line (
    id UUID,
    sales_transaction_id UUID,
    product_id INTEGER NOT NULL,
    qty INTEGER,
    price_at_sale NUMERIC(10, 2),
    origin VARCHAR(4) DEFAULT 'US'
);

-- replicated data from the EU
-- add an origin column to be able to use it as a partion

CREATE TABLE eu_sales.sales_transaction (
    id UUID,
    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_id UUID,
    origin VARCHAR(4) DEFAULT 'EU'
);

CREATE TABLE eu_sales.sales_transaction_line (
    id UUID,
    sales_transaction_id UUID,
    product_id INTEGER NOT NULL,
    qty INTEGER,
    price_at_sale NUMERIC(10, 2),
    origin VARCHAR(4) DEFAULT 'EU'
);

-- merged sales data


CREATE TABLE sales_merged.sales_transaction_merged (
    id UUID,
    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_id UUID,
    origin VARCHAR(4)
) PARTITION BY LIST (origin);

ALTER TABLE sales_merged.sales_transaction_merged ATTACH PARTITION eu_sales.sales_transaction FOR VALUES IN ('EU');
ALTER TABLE sales_merged.sales_transaction_merged ATTACH PARTITION us_sales.sales_transaction FOR VALUES IN ('US');


CREATE TABLE sales_merged.sales_transaction_line_merged (
    id UUID,
    sales_transaction_id UUID,
    product_id INTEGER NOT NULL,
    qty INTEGER,
    price_at_sale NUMERIC(10, 2),
    origin VARCHAR(4)
) PARTITION BY LIST (origin);

ALTER TABLE sales_merged.sales_transaction_line_merged ATTACH PARTITION eu_sales.sales_transaction_line FOR VALUES IN ('EU');
ALTER TABLE sales_merged.sales_transaction_line_merged ATTACH PARTITION us_sales.sales_transaction_line FOR VALUES IN ('US');
