-- [IMPROVEMENT] Rewritten procedure to be more efficient.
CREATE OR REPLACE PROCEDURE update_current_price_flags()
    LANGUAGE SQL
    AS $$
    -- This single UPDATE is more efficient than iterating.
    -- It sets 'current' to true if the current date falls within the
    -- validity range, and false otherwise.
    UPDATE product_variant_price
    SET current = (validity @> current_date);
$$;

-- \echo '--> Example maintenance queries:'
-- \echo '    1. To run the procedure to update all flags: CALL update_current_price_flags();'
-- \echo '    2. To find products/variants without a current valid price:'

-- [IMPROVEMENT] Query to find variants without a current price.
SELECT
    v.id AS variant_id,
    p.label AS product_label
FROM
    product_variant v
JOIN
    product p ON v.product_id = p.id
WHERE NOT EXISTS (
    SELECT 1
    FROM product_variant_price pvp
    WHERE pvp.product_variant_id = v.id AND pvp.current = true
);
