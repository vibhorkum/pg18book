CREATE TABLE product (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER NOT NULL REFERENCES product (id),
    product_id INTEGER NOT NULL REFERENCES product (id),
    label VARCHAR (50) NOT NULL,
    shortdescription VARCHAR(200) NOT NULL,
    longdescription TEXT,
    image_filename VARCHAR(50)
);

CREATE TABLE product_variant (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    attributes JSONB
);

CREATE TABLE product_variant_price (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_variant_id INTEGER NOT NULL REFERENCES product_variant (id) ON DELETE CASCADE,
    price NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    currency sales_currency NOT NULL,
    /*
     * DEV NOTE on `geography`:
     * Using VARCHAR(3) instead of the `sales_geo` ENUM is the correct workaround
     * for a known limitation in PostgreSQL where filtered logical replication
     * (e.g., WHERE geography = 'US') does not work with ENUM types.
    */
    geography VARCHAR(3) NOT NULL,
    -- DATERANGE where the lower bound is inclusive, and the upper bound is exclusive.
    validity DATERANGE NOT NULL,
    current BOOLEAN NOT NULL DEFAULT false,

    -- [IMPROVEMENT] Constraint to ensure currency matches the geography.
    CONSTRAINT check_currency_geo_consistency CHECK (
        (geography = 'US' AND currency = 'USD') OR
        (geography = 'EU' AND currency = 'EURO')
    ),

    -- Ensures that there are no overlapping price validity periods for the same product variant and geography.
    EXCLUDE USING GIST (product_variant_id WITH =, geography WITH =, validity WITH &&)
);

-- Set REPLICA IDENTITY to FULL for the table that has row-filtered replication.
-- This ensures that old row data is available for logical replication updates.
ALTER TABLE product_variant_price REPLICA IDENTITY FULL;


